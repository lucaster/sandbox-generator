function generateName(pattern: string): string {
  const elements = extractBracketElements(pattern);
  const parts = calcNameParts(elements);
  return replaceElementsInPatternWithWords(pattern, parts);
}
function replaceElementsInPatternWithWords(pattern: string, parts: ({ patternElement: string; word: string; } | null)[]) {
  let name = pattern;
  for (const part of parts.filter((it) => !!it)) {
    name = name.replaceAll(part.patternElement, part.word);
  }
  return name;
}
function calcNameParts(elements: string[]) {
  return elements.map((it) => {
    const table = nameTables[it];
    if (!table) {
      return null;
    }
    const patternElement = '{' + it + '}';
    const entry = randomOptionEntry(table);
    const word = entry.result;
    return {
      patternElement,
      word,
    };
  });
}
function extractBracketElements(input: string): string[] {
  return Array.from(input.matchAll(/\{([^}]+)\}/g), (match) => match[1]);
}
function generateRandomNameVariants(): string[] {
  const keys = keyNum(asd);
  const key = d(keys);
  const patterns = asd[key];

  const patternElements = extractBracketElements(patterns[0]); // B,A
  const parts = calcNameParts(patternElements);
  const variants = patterns.map(pattern => replaceElementsInPatternWithWords(pattern, parts));

  console.log(key, patterns, variants);

  return variants;
}
function generateRandomName(): string {
  const nameVariants = generateRandomNameVariants();
  const variant = nameVariants[d(nameVariants.length) - 1];
  return variant;
}

